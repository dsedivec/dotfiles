-- All three compiled production files; synthetic OS/I/O only.
local here=assert(arg[0]:match('^(.*[/\\])'))
local H=dofile(here..'dark-mode-test-support.lua')
local paths={scheduler=assert(arg[1]),locator=assert(arg[2]),entry=assert(arg[3])}
local passed,failed=0,0
local function check(name,fn)
  local ok,err=pcall(fn)
  if ok then passed=passed+1; print('PASS '..name)
  else failed=failed+1; print('FAIL '..name..': '..tostring(err)) end
end
local function online() return {ipinfo={body=H.bodies.ipinfo},ipwhois={body=H.bodies.ipwhois}} end
local function seed(when)
  local s=H.create(paths,{now=when or H.epoch(),http=online()}); s:boot(); s:advance(0); s.adm.stop(); return H.clone(s.settings)
end
check('healthy actual entry starts asynchronously, persists and schedules',function()
  local s=H.create(paths,{now=H.epoch(15,20),http=online()}); s:boot(true)
  assert(#s.tasks==0 and s.adm.status().inFlight,'startup did not defer acquisition')
  assert(s.hookCommands==1,'existing initial theme sync was not preserved')
  s:advance(0); s:assertCurrent()
  assert(s.settings[H.key].location and s.settings[H.key].solar,'successful location and solar state were not saved')
  assert(s:live()==2,'expected just watchdog + transition after success')
  local reads=s.reads; s:advance(600)
  assert(#s.tasks==1 and s.reads==reads,'healthy minute checks performed network or AppleScript work')
end)
check('denied permissions skip native requests and use IPinfo',function()
  local s=H.create(paths,{authorization='denied',http=online()}); s:boot(); s:advance(0)
  assert(s.nativeGets==0 and s.nativeNews==0,'permission denial touched native location')
  assert(s.adm.status().source=='ipinfo'); s:assertCurrent()
end)
check('fractional authorized native fix passes both components without HTTP',function()
  local now=H.epoch(15,20)
  local s=H.create(paths,{now=now,authorization='authorized',nativeFix={latitude=0,longitude=0,horizontalAccuracy=10,timestamp=now+0.7}})
  s:boot(); s:advance(0); s:assertCurrent()
  assert(#s.tasks==0 and s.adm.status().source=='corelocation','native-to-scheduler seam rejected valid fix')
  assert(s.settings[H.key].location.observedAt==now+0.7,'fractional native time changed')
end)
check('IPinfo timeout is nonblocking, falls through and rejects its late result',function()
  local s=H.create(paths,{now=H.epoch(15,18,30),http={ipinfo={hang=true},ipwhois={body=H.bodies.ipwhois,delay=1}}})
  s:boot(); local sentinel=false; s.after(1,function() sentinel=true end); s:advance(8)
  assert(sentinel and #s.tasks==2 and s.tasks[1].terminated==1,'hung source blocked the loop/fallback')
  s.tasks[1]:emit(0,H.bodies.ipinfo,200)
  assert(s.adm.status().inFlight and s.adm.status().source=='none','late timed-out provider completed current attempt')
  s:advance(1); assert(s.adm.status().source=='ipwhois'); s:assertCurrent()
  s.tasks[1]:emit(7,'synthetic private body',0)
  assert(not s.adm.status().retryScheduled and s:live()==2,'late failure revived retries')
end)
check('one sleep/wake and its watchdog tick produce one live refresh',function()
  local s=H.create(paths,{now=H.epoch(15,20),http=online()}); s:boot(); s:advance(30)
  s.now=s.now+12*3600; s:wake(); s:advance(0); s:assertCurrent()
  for _=1,10 do s:wake() end
  s:advance(60)
  assert(#s.tasks==2,'one wake was refreshed again by the clock watchdog')
  s:assertCurrent()
end)
check('offline startup without cache preserves appearance and recovers the right next event',function()
  local s=H.create(paths,{now=H.epoch(15,18,30),dark=true}); s:boot(); s:advance(0)
  assert(s.dark and s.reads==0 and s.writes==0,'empty cache invented an appearance')
  assert(s.adm.status().retryScheduled and not s.adm['get-timer'](),'empty cache did not leave a bounded retry')
  s.o.http={ipinfo={exit=7},ipwhois={body=H.bodies.ipwhois}}
  s:advance(29); assert(#s.tasks==2,'retry fired early')
  s:advance(1); assert(s.adm.status().source=='ipwhois'); s:assertCurrent()
  assert(not s.adm.status().retryScheduled and s:live()==2,'successful recovery left retry work')
end)
check('old cached coordinates immediately recalculate today and fresh recovery replaces them',function()
  local store=seed(H.epoch(1,12))
  local s=H.create(paths,{settings=store,now=H.epoch(15,18,30)}); s:boot()
  assert(s.dark and #s.tasks==0,'cached scheduling waited for network')
  assert(s.adm.status().freshness=='stale' and s.settings[H.key].solar.date=='2026-01-15')
  s:advance(0); s:assertCurrent()
  assert(s.adm.status().retryScheduled and s:live()==3,'failure removed the cached transition')
  s.o.http={ipinfo={exit=7},ipwhois={body=H.bodies.ipwhois}}; s:advance(30)
  assert(s.adm.status().freshness=='fresh' and s.adm.status().source=='ipwhois')
  s:assertCurrent(); assert(not s.dark,'fresh fixture did not replace the old cached solar day')
end)
check('all hung sources finish within the logical deadline then recover in the background',function()
  local s=H.create(paths,{now=H.epoch(15,20),authorization='authorized',http={ipinfo={hang=true},ipwhois={hang=true}}})
  s:boot(); local sentinel=false; s.after(1,function() sentinel=true end); s:advance(18)
  assert(sentinel and not s.adm.status().inFlight and s.adm.status().retryScheduled,'all-hung attempt did not complete')
  assert(s.trackers[1].stopped==1 and s.tasks[1].terminated==1 and s.tasks[2].terminated==1,'hung resources were not retired')
  s.o.authorization='denied'; s.o.http=online(); s:advance(30); s:assertCurrent()
  assert(not s.adm.status().failureCode and s:live()==2,'background recovery did not clear failure state')
end)
check('malformed providers and cache cannot escape callbacks or expose response data',function()
  local s=H.create(paths,{dark=true,settings={[H.key]='synthetic corrupt cache'},http={
    ipinfo={body='{"broken":}'},ipwhois={body='{"success":false}'}}})
  s:boot(); s:advance(0)
  assert(s.dark and s.writes==0 and #s.logs==0,'malformed data changed appearance or logged raw data')
  assert(s.adm.status().cacheError=='invalid-cache' and s.adm.status().failureCode=='all-sources-failed')
  s.o.http={ipinfo={body='{"loc":"999,0"}'},ipwhois={body=H.bodies.ipwhois}}; s:advance(30)
  assert(s.adm.status().source=='ipwhois' and not s.adm.status().cacheError); s:assertCurrent()
  local allowed={active=true,manual=true,source=true,freshness=true,solarMode=true,failureCode=true,
    failureCount=true,cacheError=true,inFlight=true,retryScheduled=true,retryInSeconds=true,transitionScheduled=true}
  for key,value in pairs(s.adm.status()) do assert(allowed[key] and type(value)~='table','status leaked location/provider fields') end
end)
check('saved same-day events expire rather than being reused as tomorrow',function()
  local store=seed(); store[H.key].location=nil
  local s=H.create(paths,{settings=store,now=H.epoch(),dark=true,solarError=true}); s:boot(); s:advance(0)
  assert(not s.dark and s.adm.status().solarMode=='saved','valid same-day solar fallback was not used')
  assert(s.adm['get-timer']():nextTrigger()==6*3600,'saved sunset transition wrong')
  s:advance(86400)
  assert(s.dark and s.adm.status().solarMode=='unavailable' and not s.adm['get-timer'](),'old absolute dates were reused')
  assert(s.adm.status().retryScheduled,'expiry stranded retry recovery')
end)
check('stale absolute events alone preserve the system state without a fake transition',function()
  local store=seed(H.epoch(1,12)); store[H.key].location=nil
  local s=H.create(paths,{settings=store,now=H.epoch(15,20)}); s:boot(); s:advance(0)
  assert(not s.dark and s.reads==0 and s.writes==0 and not s.adm['get-timer'](),'expired events were applied to a new date')
  assert(s.adm.status().retryScheduled)
end)
check('midnight reconciliation advances cached solar dates while respecting retry backoff',function()
  local s=H.create(paths,{settings=seed(),now=H.epoch(15,23,59)+30}); s:boot(); s:advance(60)
  assert(s.settings[H.key].solar.date=='2026-01-16','midnight did not recompute the local solar day')
  s:assertCurrent(); assert(#s.tasks==4 and s.adm.status().retryScheduled,'midnight bypassed an existing retry backoff')
end)
check('timezone changes move the current state and next event without duplicate fetches',function()
  local s=H.create(paths,{now=H.epoch(15,17),http=online()}); s:boot(); s:advance(0); s:assertCurrent()
  s.o.offset=3*3600; s.o.zone='SYNTHETIC+03'; s:advance(60)
  assert(s.dark and s.settings[H.key].solar.zone=='SYNTHETIC+03','timezone change was not reconciled')
  assert(#s.tasks==2,'timezone change did not coalesce its live refresh'); s:assertCurrent()
end)
check('wall-clock jumps rebase transition timers and old queued callbacks do nothing',function()
  local s=H.create(paths,{now=H.epoch(),http=online()}); s:boot(); s:advance(0)
  local old=s.adm['get-timer'](); s.now=s.now+3*3600; s:advance(60)
  local fresh=s.adm['get-timer'](); assert(old~=fresh and not old:running(),'clock jump retained the old monotonic timer')
  old.callback(); assert(s.adm['get-timer']()==fresh and s:live()==2,'stale transition displaced its replacement')
  s:assertCurrent()
end)
check('actual shutdown/reload cancels curl and isolates the replacement module generation',function()
  local s=H.create(paths,{now=H.epoch(15,20),http={ipinfo={hang=true}}}); s:boot(true); s:advance(0)
  local oldAdm=s.adm; local task=s.tasks[1]; local oldTimers={}; for _,t in ipairs(s.timers) do oldTimers[#oldTimers+1]=t end
  local oldWake=s.wakes[1]; local oldNotify=s.notifications[1]
  s.hs.shutdownCallback()
  assert(s.priorShutdowns==1 and s:live()==0 and task.terminated==1,'shutdown did not clean real components')
  s.o.http=online(); s:boot(true); s:advance(0); local writes=s.settingsWrites; local tasks=#s.tasks
  task:emit(0,H.bodies.ipwhois,200); oldWake.callback(1); oldNotify.callback()
  for _,t in ipairs(oldTimers) do t.callback() end
  assert(not oldAdm.status().active and s.settingsWrites==writes and #s.tasks==tasks,'old module mutated new lifecycle')
  assert(s:live()==2); s:assertCurrent()
end)
check('stop during native tracking detaches its callback before a replacement starts',function()
  local s=H.create(paths,{authorization='authorized',http=online()}); s:boot(); s:advance(0)
  local tracker=s.trackers[1]; local queued=tracker.fn; s.adm.stop()
  assert(s:live()==0 and tracker.fn==nil and not tracker.alive,'stop left native tracking alive')
  s.o.authorization='denied'; s:boot(); s:advance(0); local writes=s.settingsWrites
  queued(tracker,'didUpdateLocations',{{latitude=8,longitude=-9,horizontalAccuracy=10,timestamp=s.now}})
  assert(s.settingsWrites==writes and s.adm.status().source=='ipinfo','queued native fix overwrote a fresh result')
  s:assertCurrent()
end)
check('manual controls coalesce active requests and bypass backoff only explicitly',function()
  local s=H.create(paths); s:boot(); s:advance(0)
  local count=#s.tasks; for _=1,10 do s:wake() end; s:advance(0)
  assert(#s.tasks==count,'wake defeated retry backoff')
  s.o.http=online(); s.adm.update(); s.adm.start(true); s.adm.update(); s:advance(0)
  assert(#s.tasks==count+1 and not s.adm.status().retryScheduled,'manual updates duplicated or missed recovery')
  s.adm.stop(); s.adm.stop(); s.adm.update(); s:advance(86400)
  assert(s:live()==0 and #s.tasks==count+1,'stopped controls restarted background work')
end)
check('35 healthy days retain correct current and next state with one refresh per day',function()
  local s=H.create(paths,{now=H.epoch(15,20),http=online()}); s:boot(); s:advance(0)
  for day=1,35 do
    s:advance(86400); s:assertCurrent()
    assert(s.settings[H.key].solar.date==s.clock.date('%Y-%m-%d'),'healthy date stalled on day '..day)
    assert(s:live()==2 and #s.tasks<=day+2,'healthy uptime duplicated timers/requests')
  end
  assert(#s.tasks>=36,'independent daily refresh stopped')
end)
check('35 offline days retain current and next state and recover after hourly retries',function()
  local s=H.create(paths,{now=H.epoch(15,20),settings=seed()}); s:boot(); s:advance(0)
  for day=1,35 do
    s:advance(86400); s:assertCurrent()
    assert(s:live()==3 and s.adm.status().retryScheduled,'offline resources missing/duplicated on day '..day)
    assert(s.settings[H.key].solar.date==s.clock.date('%Y-%m-%d'),'offline date stalled')
    local count=#s.tasks; s:wake(); s:advance(0); assert(#s.tasks==count,'wake bypassed hourly backoff')
  end
  assert(s.adm.status().freshness=='stale' and #s.tasks>=35*24*2 and #s.tasks<=2*(35*24+10),'offline retry count unbounded or stalled')
  s.o.http=online(); s:advance(s.adm.status().retryInSeconds); s:assertCurrent()
  assert(s.adm.status().freshness=='fresh' and not s.adm.status().failureCode and s:live()==2,'multi-week recovery failed')
end)
print(('Integration: %d passed, %d failed, %d checks'):format(passed,failed,passed+failed))
os.exit(failed==0 and 0 or 1)
